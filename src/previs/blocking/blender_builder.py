"""
Blender blocking backend: the box renderer's primitives rendered by headless Blender.

The scene (triangle/quad meshes generated here from blocking.build_scene, camera matrix, colours,
light) is written to a JSON file; a fixed script (BLENDER_SCRIPT, written next to it) only reads that
JSON and renders four passes:
  1. blocking colour  - EEVEE, object colours, key-light shading, soft contact shadows (blocking_sharp.png);
  2. init colour      - the same pass with the 0.5 m reference grid hidden (blocking.png, the image-model init:
                        like the box renderer's, since Qwen renders grid lines as tiles);
  3. object ids       - Workbench flat shading, a unique colour per entity, no AA, no dithering, Standard view;
  4. depth            - Workbench Z pass through a compositor File Output node (OpenEXR float) -> depth.npy.
Blender runs as `-b --factory-startup --disable-autoexec --python <script> -- <scene.json>`: no user
preferences or add-ons, never auto-running scripts embedded in .blend files.

The id pass is decoded back to the shared id convention (entity value = index + 1), so the result is
interchangeable with BoxRenderer's. visible_frac denominators come from the box ray-caster's
unoccluded coverage of the same primitives under the same camera.
"""
